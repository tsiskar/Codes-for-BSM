def H_of_time(t, magnitude_override=None):
    """
    H(t) = [2 omega.sigma,           epsilon I]
           [epsilon I, 2 omega'(t).sigma]
    """

    omega_prime_vec = omega_prime_vector_time(t, magnitude_override)

    H_nn = 2.0 * omega_dot_sigma(omega_vec)
    H_nprime_nprime = 2.0 * omega_dot_sigma(omega_prime_vec)
