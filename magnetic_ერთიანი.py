def spinor_from_direction(direction):
    direction = direction / np.linalg.norm(direction)
    theta = np.arccos(np.clip(direction[2], -1.0, 1.0))
    phi = np.arctan2(direction[1], direction[0])
    return np.array([
        np.cos(theta / 2.0),
        np.exp(1j * phi) * np.sin(theta / 2.0)
    ], dtype=complex)

spin_direction_0 = np.cos(spin_alpha) * e_omega + np.sin(spin_alpha) * e_perp
chi_n = spinor_from_direction(spin_direction_0)
psi0 = np.array([chi_n[0], chi_n[1], 0j, 0j, 0j, 0j, 0j, 0j], dtype=complex)

