def running_time_average(t_vals, P_vals):
    """
    Return the running average

        P_bar(t) = 1 / (t - t0) integral from t0 to t of P(t') dt'

    evaluated by cumulative trapezoidal integration.  The first point is
    omitted because the average is undefined at t = t0.
    """

    t_vals = np.asarray(t_vals)
    P_vals = np.asarray(P_vals)

    dt = np.diff(t_vals)
    trapezoid_areas = 0.5 * (P_vals[:-1] + P_vals[1:]) * dt
    cumulative_area = np.cumsum(trapezoid_areas)
    elapsed_time = t_vals[1:] - t_vals[0]

    return t_vals[1:], cumulative_area / elapsed_time

