def plot_curves(ax, t, probabilities_to_plot, labels, loglog=False, linewidth=1.8):
    colors = ["black", "red", "orange", "green", "blue"]
    styles = ["-", "-", "-", "-", ":"]
    for values, label, color, style in zip(probabilities_to_plot, labels, colors, styles):
        if loglog:
            mask = (t > 0.0) & (values > 0.0)
            ax.loglog(t[mask], values[mask], color=color, linestyle=style,
                      linewidth=linewidth, label=label)
        else:
            ax.plot(t, values, color=color, linestyle=style,
                    linewidth=linewidth, label=label)

