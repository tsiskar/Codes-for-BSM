def probabilities(solution):

    P_n_up = np.abs(solution.y[0])**2
    P_n_down = np.abs(solution.y[1])**2

    P_nprime_up = np.abs(solution.y[2])**2
    P_nprime_down = np.abs(solution.y[3])**2

    P_n = P_n_up + P_n_down
    P_nprime = P_nprime_up + P_nprime_down
    P_total = P_n + P_nprime

    return (
        P_n_up,
        P_n_down,
        P_nprime_up,
        P_nprime_down,
        P_n,
        P_nprime,
        P_total
    )

