def H_of_time(t, magnitude_override=None):
    """8 x 8 Hamiltonian, written as four 2 x 2 spin blocks."""
    omega_sigma = omega_dot_sigma(omega_vec)
    omega_prime_sigma = omega_dot_sigma(
        omega_prime_vector_time(t, magnitude_override)
    )
    eps_block = epsilon * I2
    alpha_block = alpha_mix * I2
    return np.block([
        [2*omega_sigma,  zero2,         eps_block,         alpha_block],
        [zero2,        -2*omega_sigma,  alpha_block,       eps_block],
        [eps_block,    alpha_block,   2*omega_prime_sigma, zero2],
        [alpha_block,  eps_block,     zero2,             -2*omega_prime_sigma],
    ])

def rhs(t, psi, magnitude_override=None):
    return -1j * H_of_time(t, magnitude_override) @ psi

def probabilities(solution):
    P_n = np.abs(solution.y[0])**2 + np.abs(solution.y[1])**2
    P_nbar = np.abs(solution.y[2])**2 + np.abs(solution.y[3])**2
    P_nprime = np.abs(solution.y[4])**2 + np.abs(solution.y[5])**2
    P_nprimebar = np.abs(solution.y[6])**2 + np.abs(solution.y[7])**2
    return P_n, P_nbar, P_nprime, P_nprimebar, P_n + P_nbar + P_nprime + P_nprimebar

def running_time_average(t_vals, P_vals):
    dt = np.diff(t_vals)
    areas = 0.5 * (P_vals[:-1] + P_vals[1:]) * dt
    return t_vals[1:], np.cumsum(areas) / (t_vals[1:] - t_vals[0])

